/**
 * tier0-pr-creator.js — C01 Fix 5
 *
 * After new Tier-0 specs are written to tests/generated-persistent/, this
 * module auto-creates a GitHub PR so the team can review and merge them.
 *
 * Requires env vars (set in .healix/config or MCP env block):
 *   GITHUB_TOKEN      — personal access token with repo scope
 *   GITHUB_OWNER      — repo owner (e.g. "krishsharma1008")
 *   GITHUB_REPO       — repo name  (e.g. "TestBot_MCP")
 *
 * If any of the above are missing, this module is a no-op — it logs a warning
 * and returns null. The pipeline continues normally.
 */

const fs   = require('fs');
const path = require('path');

const PERSISTENT_DIR_NAME = 'generated-persistent';

/**
 * createTier0PR
 *
 * @param {object} opts
 * @param {string} opts.projectPath   - root of the repo under test
 * @param {string} opts.specFilename  - e.g. "qac-contracts-abc123.spec.ts"
 * @param {string} opts.specContent   - full file content to commit
 * @param {string} opts.baseBranch    - branch to PR against (default: current branch)
 * @returns {Promise<{prUrl: string}|null>}
 */
async function createTier0PR({ projectPath, specFilename, specContent, baseBranch = 'capillary/sabre' } = {}) {
  const token = process.env.GITHUB_TOKEN;
  const owner = process.env.GITHUB_OWNER;
  const repo  = process.env.GITHUB_REPO;

  if (!token || !owner || !repo) {
    console.warn(
      '[tier0-pr-creator] Skipping PR creation — GITHUB_TOKEN, GITHUB_OWNER, ' +
      'or GITHUB_REPO not set. Add them to your MCP env block to enable auto-PRs.'
    );
    return null;
  }

  // Lazy-load Octokit so the module is importable even without the package.
  let Octokit;
  try {
    ({ Octokit } = require('@octokit/rest'));
  } catch {
    console.warn('[tier0-pr-creator] @octokit/rest not installed. Run: npm install @octokit/rest');
    return null;
  }

  const octokit = new Octokit({ auth: token });

  // 1. Get the SHA of the base branch HEAD so we can branch from it.
  const { data: refData } = await octokit.git.getRef({
    owner,
    repo,
    ref: `heads/${baseBranch}`,
  });
  const baseSha = refData.object.sha;

  // 2. Create a new branch for this Tier-0 spec set.
  const timestamp  = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  const newBranch  = `healix/tier0-specs-${timestamp}`;
  await octokit.git.createRef({
    owner,
    repo,
    ref: `refs/heads/${newBranch}`,
    sha: baseSha,
  });

  // 3. Commit the spec file to the new branch.
  const filePath = `tests/${PERSISTENT_DIR_NAME}/${specFilename}`;
  const fileContentB64 = Buffer.from(specContent, 'utf-8').toString('base64');

  // Check if file already exists on the branch (needed for update vs create).
  let existingSha;
  try {
    const { data: existingFile } = await octokit.repos.getContent({
      owner, repo, path: filePath, ref: newBranch,
    });
    existingSha = existingFile.sha;
  } catch {
    existingSha = undefined; // file doesn't exist yet — create it
  }

  await octokit.repos.createOrUpdateFileContents({
    owner,
    repo,
    path: filePath,
    message: `test(tier0): add deterministic QA-contract specs [${specFilename}]`,
    content: fileContentB64,
    branch: newBranch,
    ...(existingSha ? { sha: existingSha } : {}),
  });

  // 4. Open the PR.
  const testCount = (specContent.match(/\btest\s*\(/g) || []).length;
  const { data: pr } = await octokit.pulls.create({
    owner,
    repo,
    title: `test(tier0): persist QA-contract specs — ${specFilename}`,
    head: newBranch,
    base: baseBranch,
    body: [
      '## Tier-0 QA Contract Specs — auto-generated by Healix',
      '',
      `**File:** \`${filePath}\``,
      `**Tests:** ${testCount}`,
      `**Spec ID:** ${specFilename}`,
      '',
      'These are deterministic contract tests produced by the Healix QA-contracts',
      'engine. They are stored in `tests/generated-persistent/` and survive AI-tier',
      'failures. They are only regenerated when the app surface changes.',
      '',
      '### What to check',
      '- [ ] Test names match real routes/selectors in the app',
      '- [ ] No false assertions (hallucinated text)',
      '- [ ] CI passes on this branch',
      '',
      '_Merge to persist these specs; close to discard._',
    ].join('\n'),
  });

  console.log(`[tier0-pr-creator] PR created: ${pr.html_url}`);
  return { prUrl: pr.html_url, branch: newBranch, prNumber: pr.number };
}

module.exports = { createTier0PR };
